def extract_tickers(prompt: str, universe=UNIVERSE) -> List[str]:
    out: List[str] = []
    low = prompt.lower()
    for name, sym in NAMES.items():
        if re.search(rf"\b{name}\b", low) and sym not in out:
            out.append(sym)
    for tok in re.findall(r"\b[A-Za-z]{1,5}\b", prompt):
        u = tok.upper()
        if (u in universe or (tok.isupper() and 2 <= len(tok) <= 5 and u not in STOP)) and u not in out:
            out.append(u)
    return out


def parse_money(prompt: str, default: float = 100_000) -> float:
    m = re.search(r"\$\s*([\d,]+(?:\.\d+)?)\s*([kKmM])?|([\d,]+(?:\.\d+)?)\s*([kKmM])\b", prompt)
    if not m:
        return default
    num = float((m.group(1) or m.group(3)).replace(",", ""))
    suf = (m.group(2) or m.group(4) or "").lower()
    return num * {"k": 1e3, "m": 1e6}.get(suf, 1)


def parse_weights(prompt: str) -> Dict[str, float]:
    w: Dict[str, float] = {}
    for a, b in re.findall(r"(\d+(?:\.\d+)?)\s*%\s*(?:in|of|to|into)?\s*([A-Za-z]{2,5})", prompt):
        if b.upper() in UNIVERSE or b.isupper():
            w[b.upper()] = float(a)
    for b, a in re.findall(r"\b([A-Z]{2,5})\b\s*[:=]?\s*(\d+(?:\.\d+)?)\s*%", prompt):
        w.setdefault(b, float(a))
    return w


def classify(prompt: str, role: str) -> Dict[str, Any]:
    p, low = prompt, prompt.lower()
    tickers = extract_tickers(p)
    weights = parse_weights(p)
    rsi_m = re.search(r"rsi\D{0,25}?(\d{2})", low)
    if re.search(r"\b(propose|request approval|paper.?trade)\b", low) and tickers:
        side = "sell" if re.search(r"\bsell|trim|reduce\b", low) else "buy"
        qty = re.search(r"(\d+)\s*(?:shares|sh)\b", low)
        return {"intent": "propose", "symbol": tickers[0], "side": side, "qty": int(qty.group(1)) if qty else 10}
    if re.search(r"\bback.?test", low) and tickers:
        return {"intent": "backtest", "symbol": tickers[0], "entry": float(rsi_m.group(1)) if rsi_m else 30.0}
    if re.search(r"\b(my )?(portfolio|holdings|book|positions)\b", low) and not weights and re.search(r"\bmy\b|review|risk|health", low):
        return {"intent": "book"}
    if weights or re.search(r"what.?if|allocation|allocate|scenario|stress|simulate|project", low) and len(tickers) >= 1 and (weights or len(tickers) >= 2):
        if not weights:
            weights = {t: 100.0 / len(tickers) for t in tickers}
        return {"intent": "whatif", "weights": weights, "capital": parse_money(p), "horizon": 126}
    if re.search(r"\bcompare|versus|\bvs\.?\b|head.?to.?head", low) and len(tickers) >= 2:
        return {"intent": "compare", "symbols": tickers[:4]}
    if re.search(r"screen|oversold|overbought|candidate|idea|find|scan|rank|best|opportunit|rsi", low) and not (
            len(tickers) == 1 and re.search(r"analy|chart|outlook", low)):
        return {"intent": "screen", "rsi_max": float(rsi_m.group(1)) if rsi_m and not re.search(r"above|over|overbought", low) else 40.0,
                "rsi_min": float(rsi_m.group(1)) if rsi_m and re.search(r"above|over|overbought", low) else None,
                "top": 5, "capital": parse_money(p)}
    if tickers:
        return {"intent": "analyze", "symbol": tickers[0]}
    return {"intent": "overview"}


