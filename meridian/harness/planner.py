rows = []
for s in snaps:
    t, f = s["technical"], s["fundamental"]
    rows.append(dict(symbol=s["symbol"], price=t["price"], rsi=t["rsi14"], trend=t["trend"], tech=t["tech_score"],
                     fund=f["fund_score"], ret_1m=t["ret_1m"], ret_3m=t["ret_3m"], vol=t["vol_20d_ann"] or 0.3,
                     pe=f["pe"], growth=f["revenue_growth_yoy"], dd=t["max_dd_6m"], regime=t["regime"]["label"],
                     macd=t["macd_hist"], flags=f["flags"], support=(t["levels"]["support"] or [None])[0],
                     sector=f["sector"], sim=bool(f["simulated_fields"])))
df = pd.DataFrame(rows)
df["score"] = (0.55 * df.tech + 0.45 * df.fund).round(1)
hit = df[{cond}].sort_values("score", ascending=False)
