if relaxed:
    hit = df.sort_values("rsi").head(TOP)
    note("No name met {label}; showing the {{}} lowest-RSI instead.".format(TOP))
pick = hit.head(TOP).copy()
inv = 1.0 / pick.vol
w = (inv / inv.sum()).clip(upper=0.4)
pick["weight"] = (w / w.sum()).round(4)
pick["shares"] = ((pick.weight * CAPITAL) / pick.price).astype(int)

for _, r in pick.iterrows():
    signal(r.symbol, price=r.price, rsi=r.rsi, trend=r.trend, tech_score=r.tech, fund_score=r.fund, pe=r.pe,
           growth=r.growth, vol=r.vol, ret_1m=r.ret_1m, ret_3m=r.ret_3m, max_dd=r.dd, regime=r.regime,
           macd_hist=r.macd, flags=r.flags, support=r.support, weight=r.weight, shares=int(r.shares), sector=r.sector,
           simulated=r.sim)

metrics([{{"label": "Universe scanned", "value": len(df)}},
         {{"label": "Pass {label}", "value": int((len(hit) if not relaxed else 0))}},
         {{"label": "Avg RSI (universe)", "value": round(float(df.rsi.mean()), 1)}},
         {{"label": "Capital (hypothetical)", "value": "$" + format(int(CAPITAL), ",")}}])
