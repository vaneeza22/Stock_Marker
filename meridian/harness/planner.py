class Planner:
    def __init__(self, llm: LLM, catalog: List[Dict[str, Any]]):
        self.llm, self.catalog = llm, catalog

    def _system(self, ctx_system: str) -> str:
        tools_txt = "\n".join(f"- {t['python']}({', '.join(t['args'])}) :: {t['description']}"
                              + ("  [HUMAN APPROVAL REQUIRED]" if t["sensitivity"] == "high" else "") for t in self.catalog)
        return f"{ctx_system}\n\n{API_DOC}\n\nTOOLS:\n{tools_txt}"

    @staticmethod
    def _extract(text: str) -> Optional[str]:
        m = re.search(r"```(?:python)?\n(.*?)```", text, re.S)
        return m.group(1).strip() if m else None

    def plan(self, prompt: str, role: str, ctx: Dict[str, Any]) -> Plan:
        spec = classify(prompt, role)
        intent = spec.pop("intent")
        if self.llm.available:
            try:
                msgs = ctx["messages"] or [{"role": "user", "content": prompt}]
                out = self.llm.complete(self._system(ctx["system"]), msgs)
                code = self._extract(out)
                if code:
                    return Plan(intent, spec, code, out.split("```")[-1].strip()[:300] or "LLM-authored analysis", "llm")
            except Exception as e:  # noqa: BLE001
                return self._template(intent, spec, f"template(fallback): LLM unavailable ({type(e).__name__})")
        return self._template(intent, spec, "template")

    def _template(self, intent: str, spec: Dict[str, Any], source: str, lite: bool = False) -> Plan:
        code = TEMPLATES[intent](spec, lite)
        rationale = {"screen": "Screen the universe, rank, size a hypothetical basket and project it.",
                     "analyze": "Pull price/indicator/fundamental data, chart it, project and back-test.",
                     "compare": "Rebase prices, compare risk/return and fundamentals side by side.",
                     "whatif": "Estimate risk, drawdown, stress and a Monte-Carlo fan for the stated weights.",
                     "overview": "Scan the whole universe for breadth, regime and leaders/laggards.",
                     "book": "Review the paper book: concentration, P&L and signal health per holding.",
                     "backtest": "Back-test the RSI rule at several thresholds against buy & hold.",
                     "propose": "Create a pending approval request (no execution)."}[intent]
        return Plan(intent, spec, code, rationale, source, lite)

    def repair(self, plan: Plan, error: str, ctx: Dict[str, Any]) -> Optional[Plan]:
        if self.llm.available and plan.source == "llm" and plan.llm_repairs < 2:   # at most two LLM repair rounds
            try:
                msgs = ctx["messages"] + [{"role": "assistant", "content": f"```python\n{plan.code}\n```"},
                                          {"role": "user", "content": f"The sandbox/validator rejected that program:\n{error}\n"
                                           "Fix it. Reply with the full corrected program in one ```python block."}]
                code = self._extract(self.llm.complete(self._system(ctx["system"]), msgs))
                if code:
                    return Plan(plan.intent, plan.params, code, "LLM self-repair", "llm", llm_repairs=plan.llm_repairs + 1)
            except Exception:  # noqa: BLE001
                pass
        # deterministic degradation: lighter version of the same template
        if plan.source.startswith("template") and not plan.lite and any(
                k in error for k in ("Timeout", "MemoryError", "SandboxCrash", "output too large")):
            return self._template(plan.intent, plan.params, "template(repair)", lite=True)
        if plan.source == "llm":  # LLM repair failed -> safe template for the same intent
            return self._template(plan.intent, plan.params, "template(fallback)")
        return None
